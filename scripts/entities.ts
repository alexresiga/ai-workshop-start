// Writes src/entities.js, the HTML5 named character references, from the WHATWG's list:
// `node scripts/entities.ts`. Only the names with a `;`, as CommonMark reads them.
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://html.spec.whatwg.org/entities.json';
const list = (await (await fetch(SOURCE)).json()) as Record<string, { characters: string }>;
const ascii = (text: string) => text.replace(/[^ -~]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
const names = Object.keys(list)
  .filter((name) => name.endsWith(';'))
  .map((name) => `${name.slice(1, -1)}:${ascii(JSON.stringify(list[name].characters))}`);
const lines = [];
for (let line = ''; names.length; ) {
  const next = names.shift()!;
  if (line && line.length + next.length > 126) lines.push(line), (line = '');
  line += (line ? ',' : '') + next;
  if (!names.length) lines.push(line);
}
writeFileSync(
  new URL('../src/entities.js', import.meta.url),
  `// The HTML5 named character references, by name, without its & and ;: ${SOURCE}.
// Generated by scripts/entities.ts; not to be edited by hand. Plain JavaScript, as markdown.js is.
export const ENTITIES = new Map(Object.entries({
${lines.map((line) => `  ${line},`).join('\n')}
}));
`,
);
